"""The UI renderers, as specs (AGENTIC_UI R8, F-01).

A UI renderer is how a UI plugin's interface reaches a host that is not
Datalayer's own page: A2UI, MCP Apps, MCP UI. One YAML per renderer under
``ui-renderers/``: its id, its name, what it does, its own documentation, and
whether it is ``enabled`` today.

A renderer is not an interface: the interface of an application is made of
its UI plugins (``ui/``, :mod:`agentspecs.ui`), and each plugin says the
renderers it may be exposed through. An application names its UI plugins and,
per plugin, the renderer.

``python -m agentspecs.ui_renderers`` writes the JSON Schema beside the specs
and the reference page of the documentation.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, List, Optional

import yaml
from pydantic import BaseModel, ConfigDict, Field, field_validator

#: The UI renderer specs.
UI_RENDERERS_DIR = Path(__file__).resolve().parent / "ui-renderers"

#: Where the JSON Schema is kept, beside the specs.
SCHEMA_PATH = UI_RENDERERS_DIR / "ui-renderer.schema.json"

#: Where the reference page is kept in the documentation site, when the checkout has one.
REFERENCE_PATH = Path(__file__).resolve().parents[1] / "docs" / "docs" / "agents" / "ui" / "renderers.md"

_ID = re.compile(r"^[a-z][a-z0-9-]{0,40}$")


class UiRendererSpec(BaseModel):
    """One UI renderer: a way a UI plugin's interface reaches a host."""

    model_config = ConfigDict(extra="forbid")

    id: str = Field(description="Its id, the file's name: what a UI plugin's `renderers` and an application's `renderer` say")
    version: str = Field(description="The version of this spec")
    name: str = Field(min_length=1, description="Its name")
    description: str = Field(min_length=1, description="What it does, in a sentence or two")
    docs_url: str = Field(description="Its own documentation, https")
    enabled: bool = Field(description="Whether an application may be exposed through it today")

    @field_validator("id")
    @classmethod
    def _an_id(cls, value: str) -> str:
        if not _ID.fullmatch(value):
            raise ValueError(f"{value!r} is not a UI renderer id: lower-case letters, digits and hyphens")
        return value

    @field_validator("docs_url")
    @classmethod
    def _https(cls, value: str) -> str:
        if not value.startswith("https://"):
            raise ValueError("a renderer's documentation is read at an https address")
        return value


def load_ui_renderers(directory: Path = UI_RENDERERS_DIR) -> Dict[str, UiRendererSpec]:
    """Every UI renderer of a directory, validated, by id; each file named for its id."""
    found: Dict[str, UiRendererSpec] = {}
    for path in sorted(directory.glob("*.yaml")):
        spec = UiRendererSpec.model_validate(yaml.safe_load(path.read_text()) or {})
        if spec.id != path.stem:
            raise ValueError(f"{path.name}: the file is named for {path.stem!r}, the spec says {spec.id!r}")
        found[spec.id] = spec
    return found


#: Every UI renderer of the catalogue, by id.
UI_RENDERER_CATALOGUE: Dict[str, UiRendererSpec] = load_ui_renderers()


def get_ui_renderer(renderer_id: str) -> Optional[UiRendererSpec]:
    """A UI renderer by id, or None."""
    return UI_RENDERER_CATALOGUE.get(renderer_id)


def json_schema() -> Dict[str, object]:
    """The JSON Schema of a UI renderer spec."""
    schema = UiRendererSpec.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://agentspecs.datalayer.tech/schemas/ui-renderer.json"
    schema["title"] = "UI renderer"
    return schema


def schema_text() -> str:
    """The JSON Schema as it is written to :data:`SCHEMA_PATH`."""
    return json.dumps(json_schema(), indent=2, sort_keys=True) + "\n"


def _cell(text: object) -> str:
    words = " ".join(str(text if text is not None else "").split())
    return words.replace("|", "\\|").replace("<", "&lt;").replace("{", "\\{").replace("}", "\\}")


def reference_text() -> str:
    """The reference page: every UI renderer, and the UI plugins each can carry."""
    from .ui import UI_CATALOGUE

    lines: List[str] = [
        "---",
        "sidebar_position: 3",
        "title: Renderers",
        "---",
        "",
        "<!-- Generated by `python -m agentspecs.ui_renderers` from ui-renderers/*.yaml. Do not edit. -->",
        "",
        "# UI renderers",
        "",
        "How a UI plugin's interface reaches a host that is not Datalayer's own page, one spec each",
        "under `agentspecs/ui-renderers/`. A renderer is not an interface: a [UI plugin](./index.mdx)",
        "says the renderers it may be exposed through, and an application names, per UI plugin, the",
        "one it uses. A renderer that is not enabled is listed, and an application that is offered",
        "cannot use it yet.",
        "",
        "| Renderer | Id | Enabled | The UI plugins it can carry |",
        "| --- | --- | --- | --- |",
    ]
    for spec in sorted(UI_RENDERER_CATALOGUE.values(), key=lambda s: s.id):
        carried = sorted(ui.id for ui in UI_CATALOGUE.values() if spec.id in ui.renderers)
        lines.append(
            f"| [{_cell(spec.name)}]({spec.docs_url}) | `{spec.id}` | {'yes' if spec.enabled else 'no'} "
            f"| {', '.join(f'`{each}`' for each in carried) or 'none yet'} |"
        )
    lines += ["", "## Each renderer", ""]
    for spec in sorted(UI_RENDERER_CATALOGUE.values(), key=lambda s: s.id):
        lines += [f"### {spec.name} (`{spec.id}`)", "", " ".join(spec.description.split()), ""]
    return "\n".join(lines)


def main() -> None:
    SCHEMA_PATH.write_text(schema_text())
    if REFERENCE_PATH.parent.is_dir():
        REFERENCE_PATH.write_text(reference_text())


if __name__ == "__main__":
    main()


__all__ = [
    "UI_RENDERER_CATALOGUE",
    "UiRendererSpec",
    "get_ui_renderer",
    "json_schema",
    "load_ui_renderers",
    "reference_text",
    "schema_text",
]
